//! Runtime snippets for linux_x86_64: the hand-written "std bits" that get
//! appended to every program needing them (emitted once, deduplicated).
//!
//! Each snippet is position-independent x86-64 machine code using only raw
//! syscalls. Addresses that depend on runtime placement (the heap base) are
//! emitted as zeros and resolved through a relocation.

/// Signed 64-bit integer → decimal text on stdout. Value arrives in `rax`.
/// Uses the machine stack as digit storage; W^X-safe.
///
/// Layout contract: the digit-loop head sits exactly 10 bytes after the
/// `jns` next-instruction address, the back-edge targets are relative to
/// it, and the digit counter (`rcx`) is zeroed BEFORE the sign branch so
/// both paths enter the loop with a valid count.
pub const ITOA: &[u8] = &[
    0x48, 0x83, 0xEC, 0x20, // sub rsp, 32        ; digit buffer on the stack
    0x49, 0x89, 0xE1, // mov r9, rsp        ; cursor = buffer start
    0x49, 0x89, 0xE0, // mov r8, rsp        ; remember start for write()
    0x31, 0xC9, // xor ecx, ecx       ; digit count (both paths!)
    0x48, 0x85, 0xC0, // test rax, rax
    0x79, 0x0A, // jns +10            ; to digit loop head
    0x41, 0xC6, 0x01, 0x2D, // mov byte [r9], '-' ; sign goes FIRST
    0x49, 0xFF, 0xC1, // inc r9
    0x48, 0xF7, 0xD8, // neg rax
    // digit loop (jns lands here):
    0x31, 0xD2, // xor edx, edx
    0x41, 0xBB, 0x0A, 0x00, 0x00, 0x00, // mov r11d, 10
    0x49, 0xF7, 0xF3, // div r11            ; rax=quot, rdx=digit
    0x80, 0xC2, 0x30, // add dl, '0'
    0x52, // push rdx           ; least significant first…
    0x48, 0xFF, 0xC1, // inc rcx
    0x48, 0x85, 0xC0, // test rax, rax
    0x75, 0xE9, // jnz -23            ; …while quotient != 0
    // fill loop (pops reverse the digits):
    0x5A, // pop rdx
    0x41, 0x88, 0x11, // mov [r9], dl
    0x49, 0xFF, 0xC1, // inc r9
    0x48, 0xFF, 0xC9, // dec rcx
    0x75, 0xF4, // jnz -12
    // write(1, buffer, len):
    0x4C, 0x89, 0xC6, // mov rsi, r8
    0x4C, 0x89, 0xCA, // mov rdx, r9
    0x48, 0x29, 0xF2, // sub rdx, rsi
    0xBF, 0x01, 0x00, 0x00, 0x00, // mov edi, 1
    0xB8, 0x01, 0x00, 0x00, 0x00, // mov eax, 1 (SYS_write)
    0x0F, 0x05, // syscall
    0x48, 0x83, 0xC4, 0x20, // add rsp, 32
    0xC3, // ret
];

/// Byte offset of the heap-base immediate inside [`alloc_snippet`] bytes
/// (the `movabs rcx, imm64` operand).
pub const ALLOC_HEAP_BASE_OFFSET: usize = 2;

/// Bump allocator over the program heap region. Size arrives in `rsi`;
/// returns the object pointer in `rax`. The bump pointer lives in the first
/// 8 bytes of the heap region and is lazily initialized.
///
/// The heap-base address is emitted as a zero placeholder; the caller
/// records an `Abs64` relocation at [`ALLOC_HEAP_BASE_OFFSET`].
pub fn alloc_snippet() -> Vec<u8> {
    let mut v = Vec::new();
    // movabs rcx, heap_base        (relocated)
    v.extend_from_slice(&[0x48, 0xB9]);
    v.extend_from_slice(&[0u8; 8]);
    // cmp qword [rcx], 0           ; first call?
    v.extend_from_slice(&[0x48, 0x83, 0x39, 0x00]);
    // jne +7                       ; skip lazy init (init block below is
    // exactly 7 bytes; landing past it executes a 32-bit `mov eax,[rcx]`
    // and truncates the bump pointer).
    v.extend_from_slice(&[0x75, 0x07]);
    // lea rdx, [rcx+8]
    v.extend_from_slice(&[0x48, 0x8D, 0x51, 0x08]);
    // mov [rcx], rdx               ; bump = heap_base + 8
    v.extend_from_slice(&[0x48, 0x89, 0x11]);
    // mov rax, [rcx]
    v.extend_from_slice(&[0x48, 0x8B, 0x01]);
    // lea rdx, [rax+rsi]
    v.extend_from_slice(&[0x48, 0x8D, 0x14, 0x30]);
    // add rdx, 15                  ; align 16
    v.extend_from_slice(&[0x48, 0x83, 0xC2, 0x0F]);
    // and rdx, -16
    v.extend_from_slice(&[0x48, 0x83, 0xE2, 0xF0]);
    // mov [rcx], rdx
    v.extend_from_slice(&[0x48, 0x89, 0x11]);
    // ret
    v.push(0xC3);
    v
}

