// Exception state (appended to the data blob only when a program uses try/catch).
//
// The block is zero-initialized and lives in the writable data section; every
// helper below takes its address as a relocated `movabs r8, <base>` (the
// relocation sits at [`EXC_BASE_OFFSET`]). Layout, from the block base:
//
//   +0   inflight exception pointer (0 = none)
//   +8   handler depth (u64)
//   +16  jmp_buf[0..MAX] — 64 bytes each:
//          +0  rbx    +8  r12   +16 r13   +24 r14
//          +32 r15    +40 rbp   +48 saved rsp (post-call)
//          +56 saved return address
//
// Total size = 16 + 64*64 = 4112 bytes.
pub const EXC_INFLIGHT_OFF: usize = 0;
pub const EXC_DEPTH_OFF: usize = 8;
pub const EXC_JMPBUFS_OFF: usize = 16;
pub const EXC_JMPBUF_SIZE: usize = 64;
pub const EXC_MAX_HANDLERS: usize = 64;
pub const EXC_STATE_SIZE: usize = EXC_JMPBUFS_OFF + EXC_JMPBUF_SIZE * EXC_MAX_HANDLERS;

/// Offset of the relocated `movabs r8, <base>` immediate inside each helper.
pub const EXC_BASE_OFFSET: usize = 2;

