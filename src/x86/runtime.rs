/// `itoa` variant writing to an arbitrary fd (`1` = stdout twin of ITOA).
///
/// The stdout [`ITOA`] constant stays byte-identical for compatibility;
/// this builds the same program with a different `edi` immediate.
pub fn itoa_to_fd(fd: u32) -> Vec<u8> {
    let mut v = ITOA.to_vec();
    debug_assert_eq!(&v[42..47], &[0xBF, 0x01, 0x00, 0x00, 0x00]);
    v[43] = fd as u8; // patch `mov edi, imm32` low byte (fd 1..255)
    v
}

